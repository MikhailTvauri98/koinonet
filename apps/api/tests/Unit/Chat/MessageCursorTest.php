<?php

declare(strict_types=1);

use App\Modules\Chat\MessageCursor;
use App\Modules\Chat\Models\Message;
use App\Support\DomainRuleException;
use Carbon\CarbonImmutable;

it('round trips microseconds and normalizes the encoded moment to UTC', function () {
    $message = new Message(['id' => '01JC0000000000000000000001']);
    $message->created_at = CarbonImmutable::parse('2026-12-01 13:00:00.123456', 'Europe/Moscow');
    $encoded = MessageCursor::encode($message);
    $decoded = MessageCursor::decode($encoded);
    expect($encoded)->toBe('2026-12-01T10:00:00.123456Z|01JC0000000000000000000001')
        ->and($decoded['id'])->toBe($message->id)
        ->and($decoded['created_at']->format('Y-m-d H:i:s.u e'))->toBe('2026-12-01 10:00:00.123456 UTC');
});

it('rejects invalid cursor timestamps and ULIDs', function (string $cursor) {
    try {
        MessageCursor::decode($cursor);
        test()->fail('Invalid cursor was accepted');
    } catch (DomainRuleException $exception) {
        expect($exception->ruleCode)->toBe('cursor.invalid');
    }
})->with([
    'nope',
    '2026-02-30T10:00:00.123456Z|01JC0000000000000000000001',
    '2026-12-01T25:00:00.123456Z|01JC0000000000000000000001',
    '2026-12-01T10:00:00Z|01JC0000000000000000000001',
    '2026-12-01T10:00:00.123456+00:00|01JC0000000000000000000001',
    '2026-12-01T10:00:00.123456Z|81JC0000000000000000000001',
    '2026-12-01T10:00:00.123456Z|01IC0000000000000000000001',
    '2026-12-01T10:00:00.123456Z|01JC0000000000000000000001|extra',
]);

it('accepts lowercase ULIDs generated by Laravel', function () {
    $decoded = MessageCursor::decode('2026-12-01T10:00:00.123456Z|01jc0000000000000000000001');
    expect($decoded['id'])->toBe('01jc0000000000000000000001');
});

it('rejects year zero unsupported by PostgreSQL', function () {
    expect(fn () => MessageCursor::decode('0000-12-01T10:00:00.123456Z|01jc0000000000000000000001'))
        ->toThrow(DomainRuleException::class);
});
